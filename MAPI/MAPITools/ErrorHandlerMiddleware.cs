using System.Text.Json;
using Microsoft.AspNetCore.Http;

namespace MAPITools
{
    public class ErrorHandlerMiddleware
    {
        // Field to store the next middleware in the pipeline
        private readonly RequestDelegate _next;
        // Constructor to initialize the middleware with the next delegate
        public ErrorHandlerMiddleware(RequestDelegate next)
        {
            // Assign the next delegate to the field
            _next = next;
        }
        // Method to handle the HTTP request
        public async Task Invoke(HttpContext context)
        {
            try
            {
                // Pass the context to the next middleware in the pipeline
                await _next(context);
            }
            catch (Exception ex) // Catch any exceptions that occur
            {
                // Handle the exception
                await HandleExceptionAsync(context, ex);
            }
        }
        // Method to handle exceptions
        private static Task HandleExceptionAsync(HttpContext context, Exception exception)
        {
            MAPIException ex = MAPIException.GetMAPIException(exception);
            // Set the response content type to JSON
            context.Response.ContentType = "application/json";
            // Set the status code to the one generated by MAPIException
            context.Response.StatusCode = ex.Codigo;
            // Create a JSON response with the error message, subcode and type
            var result = JsonSerializer.Serialize(ex.getContent());
            // Write the JSON response to the HTTP response
            return context.Response.WriteAsync(result);
        }
    }
}
